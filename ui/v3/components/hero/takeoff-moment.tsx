/**
 * TakeoffMoment — Phase 43.5 (2026-05-21).
 *
 * Replaces the §5 placeholder testimonial ("we're building in public,
 * a real one will land here") with a launch moment that visually
 * tees up the pricing section. The fake quote was honest dead air;
 * the takeoff turns it into anticipation.
 *
 * Concept (Marc's pick, "Yes — pebble-logo rocket SVG animation"):
 * the round Pebble brand mark is the rocket. On scroll-into-view
 * the pebble lifts off the bottom of the section and rises out the
 * top, leaving a vertical vapor trail behind it. The trail + a
 * pulsing downward chevron creates visual gravity that pulls the
 * eye straight down into the pricing grid below.
 *
 * No auto-scroll — on iOS scroll-jacking-without-user-intent is
 * jarring and breaks the scroll position. The animation gives the
 * "you should keep going" cue; the user does the actual scrolling.
 *
 * Background is a pre-dawn launch gradient (deep indigo top → soft
 * blue middle → cream bottom) with a sparse starfield in the dark
 * portion. Pure SVG + Framer Motion — no video assets, no Lottie.
 */

