/* =====================================================================
   Main section
   ===================================================================== */

export interface TakeoffMomentProps {
  /** Scroll target for the chevron CTA. Defaults to the page-pricing
      anchor; pass nothing in most cases. */
  scrollTo?: string;
  className?: string;
}

export function TakeoffMoment({ scrollTo = "#pricing", className = "" }: TakeoffMomentProps) {
  const prefersReduced = useReducedMotion() ?? false;
  const containerRef = React.useRef<HTMLDivElement>(null);
  const [launched, setLaunched] = React.useState(false);

  // Fire the launch when the section enters view (once). With reduced-
  // motion on, jump straight to the post-launch end state — rocket
  // hidden, trail full-height, chevron pulsing — so the visual gravity
  // toward pricing still reads.
  React.useEffect(() => {
    if (prefersReduced) { setLaunched(true); return; }
    if (typeof window === "undefined" || !containerRef.current) return;
    const io = new IntersectionObserver(
      (entries) => {
        for (const e of entries) {
          if (e.isIntersecting) {
            setLaunched(true);
            io.disconnect();
          }
        }
      },
      { threshold: 0.35 },
    );
    io.observe(containerRef.current);
    return () => io.disconnect();
  }, [prefersReduced]);

  const handleScroll = () => {
    if (!scrollTo) return;
    const target = document.querySelector(scrollTo) as HTMLElement | null;
    target?.scrollIntoView({ behavior: "smooth", block: "start" });
  };

  return (
    <div
      ref={containerRef}
      className={cn(
        "relative w-full h-full overflow-hidden",
        "bg-gradient-to-b from-[#0e1230] via-[#3b4d7a] via-50% to-background",
        className,
      )}
    >
      <Starfield />

      {/* Vapor trail — tall thin column from the bottom-center growing
          up to where the rocket exits. Linear gradient fades to
          transparent at the top so it doesn't look like a hard line. */}
      <motion.div
        aria-hidden
        initial={{ height: prefersReduced ? "82%" : 0, opacity: prefersReduced ? 0.8 : 0 }}
        animate={launched ? { height: "82%", opacity: 0.8 } : { height: 0, opacity: 0 }}
        transition={{
          height:  { duration: LAUNCH_MS / 1000, ease: EASE, delay: prefersReduced ? 0 : 0.4 },
          opacity: { duration: 0.35,                ease: EASE, delay: prefersReduced ? 0 : 0.45 },
        }}
        className="absolute left-1/2 -translate-x-1/2 bottom-0 w-[6px] sm:w-[8px] rounded-t-full pointer-events-none"
        style={{
          background:
            "linear-gradient(to top, rgba(255,255,255,0.6) 0%, rgba(255,180,140,0.45) 30%, rgba(255,200,200,0.18) 70%, rgba(255,255,255,0) 100%)",
          filter: "blur(0.5px)",
        }}
      />

      {/* The rocket itself — Pebble brand mark, lifts off from bottom-
          center to off-screen top. Hidden in the reduced-motion end
          state (already gone). */}
      <motion.div
        aria-hidden
        initial={{ y: prefersReduced ? "-110%" : "10%", opacity: prefersReduced ? 0 : 1 }}
        animate={
          launched
            ? { y: "-110%", opacity: prefersReduced ? 0 : [1, 1, 0.95, 0] }
            : { y: "10%", opacity: 1 }
        }
        transition={{
          y:       { duration: LAUNCH_MS / 1000, ease: EASE, delay: prefersReduced ? 0 : 0.4 },
          opacity: { duration: LAUNCH_MS / 1000, ease: "easeIn", delay: prefersReduced ? 0 : 0.4, times: [0, 0.6, 0.85, 1] },
        }}
        className="absolute left-1/2 -translate-x-1/2 bottom-[28%] sm:bottom-[24%] text-foreground"
      >
        <PebbleRocket className="w-14 h-20 sm:w-20 sm:h-28" />
      </motion.div>

      {/* Foreground copy — fades in just before the rocket fires. */}
      <div className="absolute inset-0 flex flex-col items-center justify-center text-center px-4 max-w-2xl mx-auto pointer-events-none">
        <motion.h2
          initial={{ opacity: 0, y: 12 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.7, ease: EASE, delay: TEXT_DELAY_MS / 1000 }}
          className="font-[family-name:var(--font-cormorant)] italic text-4xl sm:text-6xl lg:text-7xl text-white drop-shadow-[0_4px_24px_rgba(0,0,0,0.4)]"
        >
          Ready for takeoff?
        </motion.h2>
        <motion.p
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.6, ease: EASE, delay: (TEXT_DELAY_MS + 250) / 1000 }}
          className="mt-4 text-base sm:text-lg text-white/85 drop-shadow"
        >
          Pick a plan. We&apos;ll handle the rest.
        </motion.p>
      </div>

      {/* Scroll-down cue — appears after launch, pulses to signal
          "keep going, pricing is below." Clickable for kbd users +
          anyone who wants the assist. */}
      <motion.button
        type="button"
        onClick={handleScroll}
        initial={{ opacity: 0, y: -6 }}
        animate={launched ? { opacity: 1, y: 0 } : { opacity: 0, y: -6 }}
        transition={{ duration: 0.5, ease: EASE, delay: (LAUNCH_MS + 200) / 1000 }}
        aria-label="Scroll to pricing"
        className={cn(
          "absolute left-1/2 -translate-x-1/2 bottom-6 sm:bottom-8",
          "inline-flex flex-col items-center gap-1 text-white/75 hover:text-white",
          "text-[10px] uppercase tracking-[0.18em] font-semibold",
          "transition-colors duration-200",
          "focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-white/60 focus-visible:ring-offset-2 focus-visible:ring-offset-[#0e1230] rounded-md px-2 py-1",
        )}
      >
        <span>Pricing below</span>
        <motion.span
          animate={prefersReduced ? {} : { y: [0, 4, 0] }}
          transition={{ duration: 1.4, repeat: Infinity, ease: "easeInOut" }}
        >
          <ChevronDown className="w-5 h-5" aria-hidden />
        </motion.span>
      </motion.button>
    </div>
  );
}

export default TakeoffMoment;
